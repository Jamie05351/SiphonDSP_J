#!/usr/bin/env python3
"""Generates every copy of the native DSP flat-config layout from one schema file.

Source of truth: app/src/main/schema/native_bmw_dsp.schema. Generated from it (do not edit these
by hand; edit the schema and re-run this script):

  app/src/main/cpp/engine/NativeBmwDspSchema.h                C++ slot and structure constants
  app/src/main/java/app/siphondsp/model/NativeBmwDspSchema.kt  Kotlin slot indices, SIZE, DEFAULTS
  native-tests/default_config.txt                             the canonical default config
  docs/NATIVE_BMW_DSP_SCHEMA.md                               the slot-by-slot reference table

  scripts/gen-dsp-schema.py           regenerate all four
  scripts/gen-dsp-schema.py --check   exit 1 if any generated file is out of date (CI)

Schema format, one entry per line ('#' starts a comment):

  section <title>                              starts a section of the reference table
  slot <n> <default> <reader> <kotlin> <cpp> <description...>
  const <cpp-name> <value> <description...>    a structural C++ constant (width, stride, field)

<reader> is native (configure() reads and validates it: a non-finite value rejects the whole
update), kotlin (native never reads it: a Kotlin-only migration marker, UI state, or a legacy
value Kotlin migrates from), or reserved (read by nothing; kept so no later slot moves).
<kotlin> / <cpp> are the constant names for the slot, comma-separated, or '-'. Slots must appear
in order from 0, one per index.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "app/src/main/schema/native_bmw_dsp.schema"
OUT_HEADER = ROOT / "app/src/main/cpp/engine/NativeBmwDspSchema.h"
OUT_KOTLIN = ROOT / "app/src/main/java/app/siphondsp/model/NativeBmwDspSchema.kt"
OUT_DEFAULTS = ROOT / "native-tests/default_config.txt"
OUT_DOC = ROOT / "docs/NATIVE_BMW_DSP_SCHEMA.md"

READERS = {"native", "kotlin", "reserved"}
GENERATED = "Generated by scripts/gen-dsp-schema.py from app/src/main/schema/native_bmw_dsp.schema"


def parse():
    sections = []  # (title, first slot)
    slots = []
    consts = []
    for lineno, raw in enumerate(SCHEMA.read_text().splitlines(), 1):
        line = raw.split("#", 1)[0].rstrip()
        if not line.strip():
            continue
        kind, _, rest = line.strip().partition(" ")

        def fail(msg):
            sys.exit(f"{SCHEMA.name}:{lineno}: {msg}")

        if kind == "section":
            sections.append((rest.strip(), len(slots)))
        elif kind == "slot":
            parts = rest.split(None, 5)
            if len(parts) < 5:
                fail("slot needs <n> <default> <reader> <kotlin> <cpp> <description>")
            n, default, reader, kotlin, cpp = parts[:5]
            desc = parts[5] if len(parts) > 5 else ""
            if int(n) != len(slots):
                fail(f"slot {n} out of order (expected {len(slots)})")
            if reader not in READERS:
                fail(f"reader must be one of {sorted(READERS)}")
            float(default)
            slots.append(dict(
                n=int(n), default=default, reader=reader,
                kotlin=[] if kotlin == "-" else kotlin.split(","),
                cpp=[] if cpp == "-" else cpp.split(","),
                desc=desc.strip(),
            ))
        elif kind == "const":
            parts = rest.split(None, 2)
            if len(parts) < 2:
                fail("const needs <cpp-name> <value> <description>")
            consts.append(dict(name=parts[0], value=int(parts[1]), desc=parts[2] if len(parts) > 2 else ""))
        else:
            fail(f"unknown entry '{kind}'")
    names = [k for s in slots for k in s["kotlin"]]
    dup = {x for x in names if names.count(x) > 1}
    if dup:
        sys.exit(f"duplicate Kotlin names: {sorted(dup)}")
    cnames = [c for s in slots for c in s["cpp"]] + [c["name"] for c in consts]
    dup = {x for x in cnames if cnames.count(x) > 1}
    if dup:
        sys.exit(f"duplicate C++ names: {sorted(dup)}")
    return sections, slots, consts


def section_of(sections, n):
    title = ""
    for t, first in sections:
        if first <= n:
            title = t
    return title


def kotlin_float(text):
    v = float(text)
    if v == int(v) and "e" not in text.lower():
        return f"{int(v)}f"
    return f"{text}f"


def gen_header(sections, slots, consts):
    out = [
        f"// {GENERATED}.",
        "// Do not edit by hand: edit the schema, then run scripts/gen-dsp-schema.py.",
        "//",
        "// The flat float[] layout Kotlin (NativeBmwDspValues) marshals through configureNativeBmwDsp()",
        "// and NativeBmwDspProcessor::configure() reads back. Slot by slot, with what reads each one:",
        "// docs/NATIVE_BMW_DSP_SCHEMA.md. Agreement with Kotlin is checked by NativeBmwSchemaAgreementTest",
        "// (JVM) and native-tests/schema_agreement_test.cpp, which also proves every slot marked as read",
        "// by native is the one configure() consumes.",
        "#ifndef SIPHONDSP_NATIVE_BMW_DSP_SCHEMA_H",
        "#define SIPHONDSP_NATIVE_BMW_DSP_SCHEMA_H",
        "",
        "#include <array>",
        "#include <cstddef>",
        "",
        '#include "NativeBmwDspProcessor.h"',
        "",
        "namespace nbschema {",
        "",
        f"inline constexpr std::size_t kSize = {len(slots)};  // == NativeBmwDspValues.SIZE",
        "",
    ]
    last = None
    for s in slots:
        if not s["cpp"]:
            continue
        title = section_of(sections, s["n"])
        if title != last:
            out.append(f"// --- {title}")
            last = title
        for name in s["cpp"]:
            out.append(f"inline constexpr int {name} = {s['n']};")
    out.append("")
    out.append("// --- structure: block widths, strides and field offsets")
    for c in consts:
        out.append(f"inline constexpr int {c['name']} = {c['value']};  // {c['desc']}" if c["desc"]
                   else f"inline constexpr int {c['name']} = {c['value']};")
    reads = ", ".join("true" if s["reader"] == "native" else "false" for s in slots)
    out += [
        "",
        "// Whether configure() reads each slot (see the reader column of the schema).",
        f"inline constexpr std::array<bool, kSize> kReadByNative{{{{{reads}}}}};",
        "",
        "// Pinned to the processor's own copies, so a drift is a build break.",
        "static_assert(kSize == NativeBmwDspProcessor::kConfigSize);",
        "static_assert(kRoutingBase == NativeBmwDspProcessor::kRoutingBase);",
        "static_assert(kAllPassBase == NativeBmwDspProcessor::kAllPassBase);",
        "static_assert(kOutputConfigBase == NativeBmwDspProcessor::kOutputConfigBase);",
        "static_assert(kOutputConfigWidth == NativeBmwDspProcessor::kOutputConfigWidth);",
        "",
        "}  // namespace nbschema",
        "",
        "#endif",
        "",
    ]
    return "\n".join(out)


def gen_kotlin(sections, slots):
    out = [
        "// " + GENERATED + ".",
        "// Do not edit by hand: edit the schema, then run scripts/gen-dsp-schema.py.",
        "package app.siphondsp.model",
        "",
        "/**",
        " * Slot indices, size and defaults of the native DSP's flat float config, generated from",
        " * app/src/main/schema/native_bmw_dsp.schema. [NativeBmwDspValues] re-exports them; the",
        " * slot-by-slot reference is docs/NATIVE_BMW_DSP_SCHEMA.md.",
        " */",
        "object NativeBmwDspSchema {",
        f"    const val SIZE = {len(slots)}",
        "",
    ]
    last = None
    for s in slots:
        if not s["kotlin"]:
            continue
        title = section_of(sections, s["n"])
        if title != last:
            out.append(f"    // {title}")
            last = title
        for name in s["kotlin"]:
            out.append(f"    const val {name} = {s['n']}")
    out += ["", "    /** The canonical default config, one value per slot. */", "    val DEFAULTS = floatArrayOf("]
    for s in slots:
        out.append(f"        {kotlin_float(s['default'])}, // {s['n']} {s['desc']}".rstrip())
    out += [
        "    )",
        "",
        "    /** Whether the native engine reads each slot; the rest are Kotlin-only or reserved. */",
        "    val READ_BY_NATIVE = booleanArrayOf(",
    ]
    row = []
    for s in slots:
        row.append("true" if s["reader"] == "native" else "false")
        if len(row) == 8:
            out.append("        " + ", ".join(row) + ",")
            row = []
    if row:
        out.append("        " + ", ".join(row) + ",")
    out += ["    )", "}", ""]
    return "\n".join(out)


def gen_defaults(sections, slots):
    out = [
        "# " + "=" * 76,
        f"# Canonical NativeBmwDspProcessor flat-config defaults ({len(slots)} floats).",
        f"# {GENERATED}:",
        "# do not edit by hand.",
        "#",
        "# Read by native-tests/test_support.h :: defaultConfig(); NativeBmwSchemaAgreementTest checks it",
        "# equals Kotlin's NativeBmwDspValues.DEFAULTS element for element.",
        "#",
        "# One numeric value per line. '#' starts a comment; blank lines are ignored.",
        "# The index in each comment is the flat-array slot the value lands in.",
        "# " + "=" * 76,
    ]
    starts = {first: title for title, first in sections}
    for s in slots:
        if s["n"] in starts:
            out += ["", f"# {starts[s['n']]}"]
        out.append(f"{s['default']:<12} # {s['n']:<3} {s['desc']}".rstrip())
    out.append("")
    return "\n".join(out)


def gen_doc(sections, slots, consts):
    reader_text = {"native": "native", "kotlin": "Kotlin only", "reserved": "reserved"}
    counts = {r: sum(1 for s in slots if s["reader"] == r) for r in READERS}
    out = [
        "# Native DSP config schema",
        "",
        f"<!-- {GENERATED}. Do not edit by hand. -->",
        "",
        f"The flat `float[{len(slots)}]` Kotlin sends to `configureNativeBmwDsp()` and "
        "`NativeBmwDspProcessor::configure()` reads. Generated from "
        "`app/src/main/schema/native_bmw_dsp.schema`, like the C++ header "
        "(`NativeBmwDspSchema.h`), the Kotlin indices and defaults (`NativeBmwDspSchema.kt`) and "
        "`native-tests/default_config.txt`. To change the layout, edit the schema and run "
        "`scripts/gen-dsp-schema.py`; CI fails if a generated file is out of date.",
        "",
        "Slots are append-only: a retired slot is never reused for a different meaning without a "
        "migration, and nothing after it ever moves, because saved tunings are stored by index.",
        "",
        "**Reader**: *native* = `configure()` reads and validates it (a non-finite value rejects the "
        "whole update; native-tests checks this for every slot); *Kotlin only* = native never reads "
        "it (migration markers, UI state, legacy values Kotlin migrates from); *reserved* = nothing "
        "reads it.",
        "",
        f"{counts['native']} native, {counts['kotlin']} Kotlin only, {counts['reserved']} reserved.",
        "",
    ]
    starts = {first: title for title, first in sections}
    in_table = False
    for s in slots:
        if s["n"] in starts:
            out += ["", f"## {starts[s['n']]}", "", "| slot | default | reader | Kotlin | C++ | meaning |",
                    "|---:|---:|---|---|---|---|"]
            in_table = True
        if not in_table:
            out += ["| slot | default | reader | Kotlin | C++ | meaning |", "|---:|---:|---|---|---|---|"]
            in_table = True
        k = ", ".join(f"`{x}`" for x in s["kotlin"])
        c = ", ".join(f"`{x}`" for x in s["cpp"])
        out.append(f"| {s['n']} | {s['default']} | {reader_text[s['reader']]} | {k} | {c} | {s['desc']} |")
    out += ["", "## Structure constants (C++)", "", "| name | value | meaning |", "|---|---:|---|"]
    for c in consts:
        out.append(f"| `{c['name']}` | {c['value']} | {c['desc']} |")
    out.append("")
    return "\n".join(out)


def main():
    sections, slots, consts = parse()
    outputs = {
        OUT_HEADER: gen_header(sections, slots, consts),
        OUT_KOTLIN: gen_kotlin(sections, slots),
        OUT_DEFAULTS: gen_defaults(sections, slots),
        OUT_DOC: gen_doc(sections, slots, consts),
    }
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in outputs.items():
        current = path.read_text() if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.write_text(text)
    if check and stale:
        print("Out of date (edit app/src/main/schema/native_bmw_dsp.schema, then run "
              "scripts/gen-dsp-schema.py):")
        for p in stale:
            print(f"  {p}")
        return 1
    if not check:
        print("regenerated: " + (", ".join(map(str, stale)) if stale else "nothing (all up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
