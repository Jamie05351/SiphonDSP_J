package app.siphondsp.dsp

import app.siphondsp.model.BmwPeqState
import app.siphondsp.model.NativeBmwDspValues
import app.siphondsp.model.ParametricEqBand
import app.siphondsp.model.ParametricEqBandList
import app.siphondsp.model.ParametricEqChannel
import app.siphondsp.model.ParametricEqFilterType
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import kotlin.math.abs
import kotlin.math.max

/**
 * The graphs' model of the signal chain ([BmwResponseCalculator]) against what the native engine
 * actually does.
 *
 * `native-tests/golden/response_curves.txt` holds the engine's measured frequency response for a
 * set of scenarios (generated by `native-tests/response_golden.cpp`, which also fails the native
 * tests if the engine stops matching it). Here the Kotlin model computes the same scenarios on the
 * same axis and must agree, so a change to either side that makes the graphs lie fails CI.
 */
class ResponseGoldenAgreementTest {

    private class Scenario(val name: String) {
        val set = mutableListOf<Pair<Int, Float>>()
        var preampDb: Float? = null
        val bands = mutableListOf<Pair<String, ParametricEqBand>>()
        var freq = DoubleArray(0)
        var left = DoubleArray(0)
        var right = DoubleArray(0)
    }

    private class Golden(val points: Int, val minHz: Double, val maxHz: Double, val sampleRate: Double, val scenarios: List<Scenario>)

    private fun parse(file: File): Golden {
        var axis: List<Double>? = null
        val scenarios = mutableListOf<Scenario>()
        var current: Scenario? = null
        for (raw in file.readLines()) {
            val line = raw.substringBefore('#').trim()
            if (line.isEmpty()) continue
            val parts = line.split(Regex("\\s+"))
            fun doubles() = parts.drop(1).map { it.toDouble() }.toDoubleArray()
            when (parts[0]) {
                "axis" -> axis = parts.drop(1).map { it.toDouble() }
                "scenario" -> current = Scenario(parts[1]).also(scenarios::add)
                "set" -> current!!.set += parts[1].toInt() to parts[2].toFloat()
                "peq" -> current!!.preampDb = parts[1].toFloat()
                "band" -> current!!.bands += parts[1] to ParametricEqBand(
                    parts[2].toDouble(), parts[3].toDouble(), parts[4].toDouble(),
                    ParametricEqFilterType.fromCode(parts[5].toInt()),
                    ParametricEqChannel.fromCode(parts[6].toInt()),
                )
                "freq" -> current!!.freq = doubles()
                "left" -> current!!.left = doubles()
                "right" -> current!!.right = doubles()
                "end" -> current = null
                else -> error("unknown line in ${file.name}: $raw")
            }
        }
        val a = axis ?: error("no axis line in ${file.name}")
        return Golden(a[0].toInt(), a[1], a[2], a[3], scenarios)
    }

    private fun peqFor(scenario: Scenario): BmwPeqState {
        fun bank(name: String) = ParametricEqBandList().apply {
            addAll(scenario.bands.filter { it.first == name }.map { it.second })
        }
        val enabled = scenario.preampDb != null || scenario.bands.isNotEmpty()
        return if (!enabled) BmwPeqState.empty() else BmwPeqState(
            enabled = true,
            preampDb = scenario.preampDb ?: 0f,
            fullRangeBands = bank("full"),
            lowBandBands = bank("low"),
            midBandBands = bank("mid"),
            highBandBands = bank("high"),
        )
    }

    @Test
    fun graphModelMatchesTheMeasuredEngine() {
        val golden = parse(locate("native-tests/golden/response_curves.txt", "../native-tests/golden/response_curves.txt"))
        assertTrue("no scenarios", golden.scenarios.isNotEmpty())
        val calculator = BmwResponseCalculator(pointCount = golden.points)
        val curves = BmwResponseCurves(golden.points)
        val failures = mutableListOf<String>()
        for (scenario in golden.scenarios) {
            val values = NativeBmwDspValues.DEFAULTS.copyOf()
            for ((slot, value) in scenario.set) values[slot] = value
            calculator.invalidateAll()
            calculator.configureAxis(golden.sampleRate, golden.minHz, golden.maxHz)
            calculator.compute(values, peqFor(scenario), curves)
            for (i in 0 until golden.points) {
                assertEquals("${scenario.name}: axis point $i", scenario.freq[i], curves.frequencies[i], 0.01)
                for ((channel, measured) in listOf(
                    BmwOutputChannel.LEFT to scenario.left[i],
                    BmwOutputChannel.RIGHT to scenario.right[i],
                )) {
                    val modelled = curves.sumDbFor(channel)[i]
                    // Deep nulls are noise-limited in a measurement and don't show on the graph.
                    if (max(modelled, measured) < FLOOR_DB) continue
                    if (abs(modelled - measured) > TOLERANCE_DB) {
                        failures += "${scenario.name} $channel %.0f Hz: graph %.2f dB, engine %.2f dB"
                            .format(scenario.freq[i], modelled, measured)
                    }
                }
            }
        }
        assertTrue(
            "The graph model disagrees with the native engine at ${failures.size} points:\n" +
                failures.joinToString("\n"),
            failures.isEmpty(),
        )
    }

    private fun locate(vararg rels: String): File {
        var dir: File? = File(System.getProperty("user.dir") ?: ".").absoluteFile
        while (dir != null) {
            for (rel in rels) {
                val candidate = File(dir, rel)
                if (candidate.isFile) return candidate
            }
            dir = dir.parentFile
        }
        error("could not find ${rels.first()} from ${System.getProperty("user.dir")}")
    }

    private companion object {
        const val TOLERANCE_DB = 0.5
        const val FLOOR_DB = -40.0
    }
}
